-- KEY ALIASING, not name invention -- moved here from Standing Orders so every consumer gets it.
-- A station arrives either as an assignId ("Factory_Hard_02") or as the blueprint class an order
-- recorded ("BP_BuildObject_Factory_Hard_02_C"). Both are real, exact strings; only the second
-- KEY is derived, never a name.
do
    local alias = {}
    for id, name in pairs(Say.STATIONS) do
        alias["BP_BuildObject_" .. id .. "_C"] = name
        alias[id .. "_0"] = name
    end
    for k, v in pairs(alias) do if not Say.STATIONS[k] then Say.STATIONS[k] = v end end
end


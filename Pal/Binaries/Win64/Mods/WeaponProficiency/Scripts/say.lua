-- ============================================================================
--  say.lua -- the ONE place a mod turns internal data into words a player reads.
--
--  THE RULE: MAP, DO NOT TRANSFORM.
--
--  An internal id maps to a display string by explicit lookup. There is no camel-case splitting,
--  no suffix stripping, no cleverness -- because every one of those is a GUESS, and a guess that
--  looks plausible is worse than an obvious gap. That is not a theory:
--
--    "Factory_Hard_02" had a correct entry in the bench table. The lookup stripped its trailing
--    "_02" first -- a rule written for instance indices like "CoalPit_0" -- so it searched for
--    "Factory_Hard", missed, and fell through to a prettifier that produced "Factory Hard".
--    A name that reads like English and is not the game's name is the hardest kind to notice;
--    it survived four separate call-site fixes because it looked deliberate (2026-07-30).
--
--  So: one entry per EXACT string the mod can receive. A station that arrives as both
--  "CoalPit_0" and "BP_BuildObject_CoalPit_C" gets two entries. Verbose on purpose -- the table
--  is the specification, and anything absent from it is a gap the tooling can find.
--
--  VENDORED like darn.lua and ui.lua: edit here, then `node tools/sync-shared.js`.
--
--  USAGE
--    local Say = require("say")
--    Say.item(id)                    -- exact lookup in the kit's own table, or the raw id + a gap
--    Say.item(id, MY_NAMES)          -- ...checking MY_NAMES first, for a mod-specific wording
--    Say.station(id, BENCH_NAMES)
--    Say.pal(species, PAL_NAMES)
--    Say.count(1, "pal")             -- "1 pal" / "2 pals"
--    Say.list{"a","b","c"}           -- "a, b and c"
--    Say.gaps()                      -- every id that had no entry, for filling the table
-- ============================================================================


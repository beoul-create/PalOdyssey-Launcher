-- The same key aliasing the hand STATIONS table gets (see above): callers hold class names
-- ("BP_BuildObject_Furnace_C") and assign-instance ids ("Furnace_0"), while the game's table
-- keys are the bare id. Built here because the generated table does not exist yet where the
-- hand table's alias block runs.
do
    local alias = {}
    for id, name in pairs(Say.GEN_STATIONS) do
        alias["BP_BuildObject_" .. id .. "_C"] = name
        alias[id .. "_0"] = name
    end
    for k, v in pairs(alias) do
        if not Say.GEN_STATIONS[k] then Say.GEN_STATIONS[k] = v end
    end
end

-- ---- the gap register --------------------------------------------------------
-- Anything asked for and not mapped is remembered, once, per kind. This is how a missing entry
-- becomes a to-do instead of a shrug: dump it in a boot report, or have a test assert it is
-- empty for the ids a mod actually uses.
local gaps = { item = {}, station = {}, pal = {} }
local gapLog = nil

function Say.onGap(fn) gapLog = fn end          -- optional: log the first sighting of each gap

local function miss(kind, id)
    local k = tostring(id)
    if not gaps[kind][k] then
        gaps[kind][k] = true
        if gapLog then pcall(gapLog, kind, k) end
    end
    -- The RAW ID is returned deliberately. It is ugly, and it should be: an unmapped id is a bug
    -- with a visible symptom, and a prettified stand-in would hide it behind something that reads
    -- like a real name.
    return k
end

function Say.gaps(kind)
    local out = {}
    for k in pairs(kind and (gaps[kind] or {}) or {}) do out[#out + 1] = k end
    if not kind then
        for _, tbl in pairs(gaps) do
            for k in pairs(tbl) do out[#out + 1] = k end
        end
    end
    table.sort(out)
    return out
end

-- ---- the lookups -------------------------------------------------------------
-- All three are the same shape: exact match, else record the gap and hand back the id.
-- Case-insensitive as a SAFETY NET only -- the game hands back "GunPowder2" where a table says
-- "Gunpowder2", and one capital should not cost a real name. It is not a transform: the string
-- still has to be in the table.
local lowerCache = setmetatable({}, { __mode = "k" })
-- `names` is the CALLER'S map and is checked first; `shared` is the kit's own table for this
-- kind. Two passes of the same exact-match rule -- no transforms in either.
local function lookup(kind, id, names, shared, gen)
    if id == nil then return "?" end
    local k = tostring(id)
    -- NOT ipairs{ names, shared }: with no caller map that table is { nil, shared }, whose
    -- length is 0, so the loop would never run and EVERY name would miss. An explicit
    -- nil-guarded call per table instead -- the caller's first, then the kit's hand table
    -- (the override point), then the GENERATED table (the game's own English text, see
    -- gen-saynames.js). Order matters: a hand entry is a deliberate wording and must beat
    -- the extraction.
    local function try(t)
        if not t then return nil end
        if t[k] then return t[k] end
        local lut = lowerCache[t]
        if not lut then
            lut = {}
            for a, b in pairs(t) do lut[string.lower(a)] = b end
            lowerCache[t] = lut
        end
        return lut[string.lower(k)]
    end
    return try(names) or try(shared) or try(gen) or miss(kind, k)
end

function Say.item(id, names)      return lookup("item", id, names, Say.ITEMS, Say.GEN_ITEMS) end
function Say.station(id, names)   return lookup("station", id, names, Say.STATIONS, Say.GEN_STATIONS) end

-- Pals are the one place a mechanical rule is DEFENSIBLE, and it is still only a fallback:
-- BOSS_/GYM_/RAID_ are documented variant prefixes the game itself does not display, and the
-- stripped result is looked up again rather than shown directly. If neither form is mapped it
-- is still a gap.
function Say.pal(species, names)
    if species == nil then return "?" end
    local k = tostring(species)
    -- same nil trap as lookup(): a caller with no map must still reach Say.PALS
    local function hit(key)
        if names and names[key] then return names[key] end
        if Say.PALS and Say.PALS[key] then return Say.PALS[key] end
        if Say.GEN_PALS and Say.GEN_PALS[key] then return Say.GEN_PALS[key] end
        return nil
    end
    local direct = hit(k)
    if direct then return direct end
    local bare = k:gsub("^BOSS_", ""):gsub("^GYM_", ""):gsub("^RAID_", ""):gsub("_Otomo$", "")
    if bare ~= k then
        local v = hit(bare)
        if v then return v end
    end
    return miss("pal", k)
end

-- ---- small grammar helpers ----------------------------------------------------
-- The `(n == 1) and "" or "s"` dance appeared a dozen times and was written wrong twice.
function Say.count(n, singular, plural)
    n = tonumber(n) or 0
    local word = (n == 1) and singular or (plural or (singular .. "s"))
    return string.format("%d %s", n, word)
end

function Say.list(items, conj)
    conj = conj or "and"
    local t = {}
    for _, v in ipairs(items or {}) do t[#t + 1] = tostring(v) end
    if #t == 0 then return "" end
    if #t == 1 then return t[1] end
    local last = table.remove(t)
    return table.concat(t, ", ") .. " " .. conj .. " " .. last
end

-- ---- the safety net ------------------------------------------------------------
-- First internal-looking fragment in a COMPOSED string, or nil. tools/copy-check.js enforces the
-- same patterns statically; this is for a runtime assertion while developing.
local SMELLS = {
    { "%f[%w]BP_[%w_]+",            "a blueprint class name" },
    { "[%w_]+_C%f[%W]",             "a blueprint class suffix" },
    { "@%x%x%x%x%x%x%x%x",          "an instance GUID" },
    { "%f[%w][%u][%w]*_[%u][%w_]*", "an internal id" },
    { ">=",                         "a maths operator" },
    { "%f[%w]%w+=%w+",              "a debug key=value" },
    { "%f[%w]nil%f[%W]",            "a nil leaking into text" },
}
function Say.audit(text)
    local s = tostring(text or "")
    for _, rule in ipairs(SMELLS) do
        local hit = s:match(rule[1])
        if hit then return hit, rule[2] end
    end
    return nil
end

return Say
